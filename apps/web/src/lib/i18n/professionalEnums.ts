const enumText = createTranslator(professionalEnumMessages);
export function professionalEnumLabel(label: string, code?: string): string {
  if (!Object.hasOwn(professionalEnumMessages, label))
    throw new TypeError(`Unknown controlled professional caption: ${label}`);
  // Shared Chinese captions can have distinct meanings in existing enum contracts.
  // Preserve the original Chinese label while disambiguating English by stable code.
  if (getLocale() === "zh-CN") return label;
  if (label === "申报" && code === "filed") return enumText("已申报");
  if (label === "合作方" && code === "partner") return enumText("交易合作方");
  return enumText(label as keyof typeof professionalEnumMessages);
}
