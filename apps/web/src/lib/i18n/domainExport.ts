export const domainExportText = createTranslator(domainExportMessages);
/** Only controlled catalog headings use this adapter; raw export data stays untouched. */
export function domainExportLabel(label: string): string {
  if (!Object.hasOwn(domainExportMessages, label)) throw new TypeError(`Unknown export heading: ${label}`);
  return domainExportText(label as keyof typeof domainExportMessages);
}
